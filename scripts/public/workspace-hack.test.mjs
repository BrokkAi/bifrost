import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

import { prepareReleaseWorkspace } from "./with-release-workspace.mjs";

const scripts = fileURLToPath(new URL(".", import.meta.url));
const retainedDependency = `[[package]]
name = "feature-dependency"
version = "7.8.9"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${"a".repeat(64)}"

`;
const retainedFeature = 'feature-dependency = { version = "=7.8.9", features = ["retained"] }';

function fixture(body) {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "bifrost-hack-contract-"));
  try { return body(temporary); }
  finally { fs.rmSync(temporary, { recursive: true, force: true }); }
}

function write(root, relative, text) {
  const file = path.join(root, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

function workspace(root) {
  write(root, "Cargo.toml", `[workspace]
members = [
    "crates/workspace-hack",
]
resolver = "3"
[workspace.dependencies]
workspace-hack = { path = "crates/workspace-hack" }
[workspace.metadata.cargo-machete]
ignored = ["workspace-hack"]

[package.metadata.cargo-machete]
ignored = ["workspace-hack"]

[package]
name = "bifrost-hakari-package-contract"
version = "1.2.3"
edition = "2024"
description = "Archive isolation contract"
license = "Apache-2.0"
[dependencies]
${retainedFeature}
workspace-hack.workspace = true
`);
  write(root, "src/lib.rs", "pub fn archive_contract() {}\n");
  write(root, "crates/workspace-hack/Cargo.toml", '[package]\nname = "workspace-hack"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n');
  write(root, "crates/workspace-hack/src/lib.rs", "");
  write(root, ".config/hakari.toml", 'hakari-package = "workspace-hack"\n');
  // A handwritten registry fixture keeps this archive contract offline.
  write(root, ".cargo/config.toml", '[source.crates-io]\nreplace-with = "fixture-registry"\n[source.fixture-registry]\ndirectory = "vendor"\n');
  write(root, "vendor/feature-dependency/Cargo.toml", '[package]\nname = "feature-dependency"\nversion = "7.8.9"\nedition = "2024"\n[features]\nretained = []\n');
  write(root, "vendor/feature-dependency/src/lib.rs", "pub fn retained_feature() {}\n");
  write(root, "vendor/feature-dependency/.cargo-checksum.json", JSON.stringify({ package: "a".repeat(64), files: {} }));
  write(root, "Cargo.lock", `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "bifrost-hakari-package-contract"
version = "1.2.3"
dependencies = [
 "feature-dependency",
 "workspace-hack",
]

${retainedDependency}[[package]]
name = "workspace-hack"
version = "0.1.0"
`);
}

test("a release copy packages with a locked graph and leaves its input untouched", () => fixture(temporary => {
  const source = path.join(temporary, "checkout");
  const destination = path.join(temporary, "prepared");
  workspace(source);
  write(source, "target/unused", "must not copy compiler artifacts");
  write(source, "node_modules/unused", "must not copy downloaded tooling");
  write(source, ".claude/worktrees/other-checkout/unused", "must not copy nested worktrees");
  const beforeManifest = fs.readFileSync(path.join(source, "Cargo.toml"), "utf8");
  const beforeLock = fs.readFileSync(path.join(source, "Cargo.lock"), "utf8");
  prepareReleaseWorkspace(source, destination);

  const expectedLock = beforeLock.replace(' "workspace-hack",\n', "")
    .replace('[[package]]\nname = "workspace-hack"\nversion = "0.1.0"\n', "");
  assert.equal(fs.readFileSync(path.join(destination, "Cargo.lock"), "utf8"), expectedLock);
  assert.ok(expectedLock.includes(retainedDependency), "retain the registry dependency block and exact version");
  assert.ok(fs.readFileSync(path.join(destination, "Cargo.toml"), "utf8").includes(retainedFeature),
    "retain the third-party dependency's explicit feature declaration byte for byte");
  assert.ok(!fs.existsSync(path.join(destination, "target")));
  assert.ok(!fs.existsSync(path.join(destination, "node_modules")));
  assert.ok(!fs.existsSync(path.join(destination, ".claude")));
  assert.throws(() => prepareReleaseWorkspace(source, path.join(source, "..nested")), /outside the source tree/);
  const result = spawnSync("cargo", ["package", "--locked", "--allow-dirty", "--no-verify", "--offline"], {
    cwd: destination, encoding: "utf8",
  });
  assert.equal(result.status, 0, result.stderr);
  assert.equal(fs.readFileSync(path.join(source, "Cargo.toml"), "utf8"), beforeManifest);
  assert.equal(fs.readFileSync(path.join(source, "Cargo.lock"), "utf8"), beforeLock);
}));

test("the release wrapper preserves failure status and removes the disposable source", () => fixture(temporary => {
  const source = path.join(temporary, "checkout");
  workspace(source);
  write(source, "scripts/public/with-release-workspace.mjs", fs.readFileSync(path.join(scripts, "with-release-workspace.mjs"), "utf8"));
  const manifest = fs.readFileSync(path.join(source, "Cargo.toml"), "utf8");
  const result = spawnSync(process.execPath, [path.join(source, "scripts/public/with-release-workspace.mjs"),
    process.execPath, "-e", 'console.log(process.cwd()); process.exit(7);'], { encoding: "utf8" });
  assert.equal(result.status, 7, result.stderr);
  const prepared = result.stdout.trim();
  assert.match(prepared, /bifrost-release-source-/);
  assert.ok(!fs.existsSync(prepared));
  assert.equal(fs.readFileSync(path.join(source, "Cargo.toml"), "utf8"), manifest);
}));

test("machete metadata follows renamed generated dependencies and fails closed on drift", () => fixture(temporary => {
  write(temporary, "scripts/public/workspace-hack.mjs", fs.readFileSync(path.join(scripts, "workspace-hack.mjs"), "utf8"));
  write(temporary, "crates/workspace-hack/Cargo.toml", '[package]\nname = "workspace-hack"\nversion = "0.1.0"\n');
  write(temporary, "dependencies.json", JSON.stringify([
    { name: "syn", rename: "syn-version-two" }, { name: "serde", rename: null }, { name: "serde", rename: null },
  ]));
  const fakeCargo = `#!${process.execPath}
import fs from "node:fs";
fs.appendFileSync("calls.jsonl", JSON.stringify(process.argv.slice(2)) + "\\n");
if (process.argv[2] === "metadata") console.log(JSON.stringify({packages:[{name:"workspace-hack", dependencies:JSON.parse(fs.readFileSync("dependencies.json", "utf8"))}]}));
`;
  write(temporary, "bin/package.json", '{"type":"module"}\n');
  write(temporary, "bin/cargo", fakeCargo);
  fs.chmodSync(path.join(temporary, "bin/cargo"), 0o755);
  const command = path.join(temporary, "scripts/public/workspace-hack.mjs");
  const env = { ...process.env, PATH: `${path.join(temporary, "bin")}${path.delimiter}${process.env.PATH}` };
  execFileSync(process.execPath, [command], { env });
  const generated = fs.readFileSync(path.join(temporary, "crates/workspace-hack/Cargo.toml"), "utf8");
  assert.match(generated, /ignored = \["serde","syn-version-two"\]/);
  execFileSync(process.execPath, [command, "--check"], { env });
  const calls = fs.readFileSync(path.join(temporary, "calls.jsonl"), "utf8").trim().split("\n").map(JSON.parse);
  assert.ok(calls.some(call => JSON.stringify(call) === JSON.stringify(["hakari", "generate", "--diff"])));
  assert.ok(calls.some(call => JSON.stringify(call) === JSON.stringify(["hakari", "manage-deps", "--dry-run"])));
  write(temporary, "dependencies.json", JSON.stringify([{ name: "new-dependency", rename: null }]));
  const drift = spawnSync(process.execPath, [command, "--check"], { env, encoding: "utf8" });
  assert.notEqual(drift.status, 0);
  assert.match(drift.stderr, /metadata is stale/);
  assert.equal(fs.readFileSync(path.join(temporary, "crates/workspace-hack/Cargo.toml"), "utf8"), generated);
}));
