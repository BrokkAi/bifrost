#!/usr/bin/env node

// Package without the unpublished build aid, without editing a live checkout.
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export function prepareReleaseWorkspace(source, destination) {
  source = path.resolve(source);
  destination = path.resolve(destination);
  const relative = path.relative(source, destination);
  assert.ok(path.isAbsolute(relative) || relative === ".." || relative.startsWith(`..${path.sep}`),
    "release copy must be outside the source tree");
  const omitted = new Set([".git", "target", "dist", ".agents", ".mj", ".mjolnir", ".claude", ".codex", ".cache", ".brokk"]);
  fs.cpSync(source, destination, {
    recursive: true,
    filter(file) {
      const parts = path.relative(source, file).split(path.sep);
      return !omitted.has(parts[0]) && !parts.includes("node_modules") && !parts.includes("__pycache__");
    },
  });

  // These are the exact shapes generated by hakari's workspace-dotted style.
  // Reject drift rather than quietly packaging a dependency we failed to remove.
  const rootManifest = path.join(destination, "Cargo.toml");
  let root = fs.readFileSync(rootManifest, "utf8");
  const member = /^\s*"crates\/workspace-hack",\r?\n/gm;
  const dependency = /^workspace-hack = \{ path = "crates\/workspace-hack" \}\r?\n/gm;
  const workspaceIgnored = /^\[workspace\.metadata\.cargo-machete\]\r?\nignored = \["workspace-hack"\]\r?\n/gm;
  const packageIgnored = /^\[package\.metadata\.cargo-machete\]\r?\nignored = \["workspace-hack"\]\r?\n/gm;
  for (const pattern of [member, dependency, workspaceIgnored, packageIgnored]) {
    assert.equal([...root.matchAll(pattern)].length, 1, `missing generated manifest entry: ${pattern}`);
    root = root.replace(pattern, "");
  }
  fs.writeFileSync(rootManifest, root);

  const manifests = [rootManifest, ...fs.readdirSync(path.join(destination, "crates"))
    .filter(name => name !== "workspace-hack")
    .map(name => path.join(destination, "crates", name, "Cargo.toml"))
    .filter(file => fs.existsSync(file))];
  for (const file of manifests) {
    const text = fs.readFileSync(file, "utf8");
    const edge = /^workspace-hack\.workspace = true\r?\n/gm;
    assert.equal([...text.matchAll(edge)].length, 1, `${file} must have one generated workspace-hack dependency`);
    const stripped = text.replace(edge, "");
    assert.ok(!stripped.includes("workspace-hack"), `${file} retains a workspace-hack reference`);
    fs.writeFileSync(file, stripped);
  }

  const lockPath = path.join(destination, "Cargo.lock");
  const lock = fs.readFileSync(lockPath, "utf8");
  const blocks = lock.split(/(?=^\[\[package\]\]\r?$)/m);
  const hack = /^\[\[package\]\]\r?\nname = "workspace-hack"\r?\n/;
  assert.equal(blocks.filter(block => hack.test(block)).length, 1, "lockfile must contain one workspace-hack package");
  const strippedLock = blocks.filter(block => !hack.test(block)).join("").replace(/^ "workspace-hack",\r?\n/gm, "");
  assert.ok(!strippedLock.includes('"workspace-hack"'), "lockfile retains a workspace-hack reference");
  fs.writeFileSync(lockPath, strippedLock);
  fs.rmSync(path.join(destination, "crates", "workspace-hack"), { recursive: true });
  fs.rmSync(path.join(destination, ".config", "hakari.toml"));
}

async function main() {
  const source = fileURLToPath(new URL("../../", import.meta.url));
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "bifrost-release-source-"));
  const destination = path.join(temporary, "source");
  try {
    prepareReleaseWorkspace(source, destination);
    const [command, ...args] = process.argv.slice(2);
    assert.ok(command, "usage: with-release-workspace.mjs COMMAND [ARG ...]");
    const child = spawn(command, args, {
      cwd: destination,
      stdio: "inherit",
      env: {
        ...process.env,
        DIST_DIR: path.resolve(source, process.env.DIST_DIR ?? "dist"),
      },
    });
    const signals = ["SIGINT", "SIGTERM"];
    const handlers = signals.map(signal => () => { child.kill(signal); });
    signals.forEach((signal, i) => process.on(signal, handlers[i]));
    try {
      const status = await new Promise((resolve, reject) => {
        child.once("error", reject);
        child.once("exit", (code, signal) => resolve(code ?? (signal === "SIGINT" ? 130 : 143)));
      });
      process.exitCode = status;
    } finally {
      signals.forEach((signal, i) => process.off(signal, handlers[i]));
    }
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await main();
}
