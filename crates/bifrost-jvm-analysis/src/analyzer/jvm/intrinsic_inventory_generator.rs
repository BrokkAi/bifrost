#[test]
#[ignore = "offline artifact generator; requires explicitly supplied pinned stdlib inputs"]
fn generate_intrinsic_provider_inventories() {
    let root =
        PathBuf::from(std::env::var_os("JVM_INTRINSIC_ARTIFACTS").expect("artifact directory"));
    let output = PathBuf::from(std::env::var_os("JVM_INTRINSIC_OUTPUT").expect("output file"));
    let commit = std::env::var("JVM_INTRINSIC_GENERATOR_COMMIT").expect("generator commit");
    let limits = ArtifactProducerLimits {
        max_records: 1_000_000,
        max_diagnostics: 10_000,
        ..ArtifactProducerLimits::default()
    };
    let mut packages = BTreeMap::<String, BTreeSet<String>>::new();
    let mut members = BTreeMap::<String, BTreeSet<(String, String)>>::new();
    let mut parents = BTreeMap::<String, BTreeSet<String>>::new();
    let mut audits = Vec::new();
    let mut kotlin_members = OwnerMembers::new();
    let mut kotlin_parents = BTreeMap::<String, BTreeSet<String>>::new();
    let mut coverage_failures = Vec::new();
    let mut generated = format!(
        "// Generated by intrinsic_inventory_generator.rs at {commit}.\n// Name presence only; present names do not provide callable or type detail.\n"
    );
    for (name, version, language, extension) in [
        (
            "kotlin-stdlib-2.1.20-sources.jar",
            "2.1.20",
            Language::Kotlin,
            ".kt",
        ),
        (
            "kotlin/kotlin-stdlib-2.2.20-sources.jar",
            "2.2.20",
            Language::Kotlin,
            ".kt",
        ),
        (
            "kotlin/kotlin-stdlib-2.3.20-sources.jar",
            "2.3.20",
            Language::Kotlin,
            ".kt",
        ),
        (
            "scala-library-2.13.16-sources.jar",
            "2.13.16",
            Language::Scala,
            ".scala",
        ),
        (
            "scala3-library_3-3.3.5-sources.jar",
            "3.3.5",
            Language::Scala,
            ".scala",
        ),
    ] {
        let closure_only = language == Language::Kotlin && version != "2.1.20";
        let artifact = read_exact_artifact_while(&root.join(name), &limits, || false).unwrap();
        let mut diagnostics = BoundedProducerDiagnostics::new(&limits);
        let entries = crate::analyzer::jvm::source_archive_entries(
            &artifact,
            &[extension, ".java"],
            language.config_label(),
            if language == Language::Kotlin {
                1_024
            } else {
                usize::MAX
            },
            &limits,
            None,
            &mut diagnostics,
        )
        .unwrap();
        let (diagnostics, suppressed) = diagnostics.finish();
        assert!(
            diagnostics.is_empty() && suppressed.total() == 0,
            "{diagnostics:#?}; {suppressed:#?}"
        );
        let mut included_files = 0;
        let mut recovered = Vec::new();
        let mut included_packages = BTreeSet::new();
        let mut files = Vec::new();
        let included = |package: &str| match language {
            Language::Kotlin => KOTLIN_DEFAULT_IMPORT_PACKAGES
                .iter()
                .any(|p| p.rendered == package),
            Language::Scala => package == "scala",
            _ => unreachable!(),
        };
        for (path, source) in &entries {
            if path.ends_with(".java") {
                if closure_only {
                    continue;
                }
                let index = crate::analyzer::jvm::java_artifact::source_declaration_index(source)
                    .expect("Java source name reader returns a tree");
                let names = index.top_level_names.into_iter().collect::<BTreeSet<_>>();
                let is_included = included(&index.package_name);
                if is_included {
                    included_files += 1;
                    included_packages.insert(index.package_name.clone());
                    if names.is_empty() {
                        coverage_failures.push(format!(
                            "{name}:{path}: Java default package {:?} yielded zero names",
                            index.package_name
                        ));
                    }
                    packages
                        .entry(index.package_name.clone())
                        .or_default()
                        .extend(names.iter().cloned());
                }
                // Reuse the canonical Java package segment helper, rather than
                // scanning a Java package declaration or parsing source text.
                let segments = brokk_bifrost_core::analyzer::fq_name::joined_segments(
                    &index.package_name,
                    ".",
                )
                .collect::<Vec<_>>();
                if language == Language::Scala && segments.len() > 1 && segments[0] == "scala" {
                    packages
                        .entry("scala".to_owned())
                        .or_default()
                        .insert(segments[1].to_owned());
                }
                let audit = serde_json::json!({"file": path, "language": "java", "packages": [&index.package_name],
                    "fallback_package": index.package_name, "included": is_included, "names": names,
                    "provider_remapping": null});
                if index.recovered {
                    recovered.push(audit.clone());
                }
                files.push(audit);
                continue;
            }
            let (tree, parsed) = match language {
                Language::Kotlin => KotlinSourceJarPackProducer.parse_names(source),
                Language::Scala => ScalaSourceJarPackProducer.parse_names(source),
                _ => unreachable!(),
            };
            let file_packages = parsed
                .declarations()
                .iter()
                .filter(|unit| !unit.is_synthetic() && unit.declaration_segment_count() == 1)
                .map(|unit| unit.package_name().to_owned())
                .collect::<BTreeSet<_>>();
            let fallback_package = if language == Language::Scala {
                brokk_bifrost_jvm::scala::graph::syntax::ScalaPackageContextIndex::new(
                    tree.root_node(),
                    source,
                )
                .prefixes_at(source.len().saturating_sub(1))
                .last()
                .cloned()
                .unwrap_or_default()
            } else {
                parsed.package_name.clone()
            };
            if language == Language::Kotlin {
                collect_kotlin_closure_inputs(
                    &tree,
                    &parsed,
                    source,
                    &mut kotlin_members,
                    &mut kotlin_parents,
                );
            }
            if closure_only {
                continue;
            }
            let mut top_names = BTreeSet::new();
            let parent_index = crate::analyzer::jvm::parent_index(&parsed);
            let canonical = parsed
                .source_facts
                .as_ref()
                .and_then(|facts| facts.scala.as_ref());
            for declaration in parsed
                .declarations()
                .iter()
                .filter(|unit| !unit.is_synthetic())
            {
                let owner = scala_normalize_full_name(&declaration.fq_name());
                if declaration.declaration_segment_count() == 1
                    && included(declaration.package_name())
                {
                    let name = declaration.terminal_name().to_owned();
                    top_names.insert(name.clone());
                    included_packages.insert(declaration.package_name().to_owned());
                    packages
                        .entry(declaration.package_name().to_owned())
                        .or_default()
                        .insert(name);
                }
                if let Some(parent) = parent_index.get(declaration) {
                    let parent_name = scala_normalize_full_name(&parent.fq_name());
                    let visibility = canonical
                        .and_then(|canonical| {
                            let id = parsed
                                .source_declaration_units
                                .iter()
                                .find_map(|(id, unit)| (unit == declaration).then_some(*id))?;
                            canonical
                                .declarations
                                .iter()
                                .find(|fact| fact.declaration == id)
                        })
                        .map_or("public", |fact| match fact.visibility {
                            ScalaDeclarationVisibility::Protected => "protected",
                            ScalaDeclarationVisibility::NonApi => "private",
                            _ => "public",
                        });
                    members.entry(parent_name).or_default().insert((
                        declaration.terminal_name().to_owned(),
                        visibility.to_owned(),
                    ));
                }
                if language == Language::Scala {
                    for segments in
                        source_parent_paths(language, &tree, &parsed, declaration, source)
                    {
                        let path = qualify_source_parent(declaration.package_name(), &segments);
                        parents.entry(owner.clone()).or_default().insert(path);
                    }
                }
            }
            let mut recovered_names = BTreeSet::new();
            if language == Language::Scala {
                // Audit direct declaration fields independently of CodeUnits:
                // operator-named classes and empty package objects are not all
                // represented by the workspace display declaration reader.
                for recovered_name in scala_top_level_names(tree.root_node(), source) {
                    if top_names.insert(recovered_name.clone()) {
                        recovered_names.insert(recovered_name.clone());
                    }
                    packages
                        .entry("scala".to_owned())
                        .or_default()
                        .insert(recovered_name);
                }
                // Scala's package wildcard also imports immediate subpackages.
                // Read their segments from CodeUnit package identities.
                let interner = brokk_bifrost_core::analyzer::fq_name::segment_interner();
                for unit in parsed.declarations() {
                    let package = unit.package_fq();
                    if package.len() > 1 && interner.resolve(package.segments()[0]).0 == "scala" {
                        packages
                            .entry("scala".to_owned())
                            .or_default()
                            .insert(interner.resolve(package.segments()[1]).0.to_owned());
                    }
                }
            }
            // Scala 3's compiler patches these declarations into the real
            // scala.Predef. Their source package is not the imported owner.
            let patches_predef = language == Language::Scala
                && parsed.declarations().iter().any(|unit| {
                    scala_normalize_full_name(&unit.fq_name())
                        == "scala.runtime.stdLibPatches.Predef"
                });
            if patches_predef {
                top_names.extend(
                    members
                        .get("scala.runtime.stdLibPatches.Predef")
                        .expect("Predef patch has named members")
                        .iter()
                        .map(|(name, _)| name.clone()),
                );
                included_packages.insert(parsed.package_name.clone());
            }
            let is_included = file_packages.iter().any(|package| included(package))
                || (file_packages.is_empty() && included(&fallback_package))
                || patches_predef;
            if is_included {
                included_files += 1;
                if top_names.is_empty() {
                    coverage_failures.push(format!(
                        "{name}:{path}: default package {fallback_package:?} yielded zero names"
                    ));
                }
            }
            if tree.root_node().has_error() || !recovered_names.is_empty() {
                recovered.push(
                    serde_json::json!({"file": path, "packages": file_packages, "fallback_package": fallback_package,
                    "included": is_included, "names": top_names, "additional_names": recovered_names}),
                );
            }
            files.push(
                serde_json::json!({"file": path, "packages": file_packages, "fallback_package": fallback_package,
                "included": is_included, "names": top_names,
                "provider_remapping": patches_predef.then_some("scala.Predef")}),
            );
        }
        writeln!(
            generated,
            "// {name}, version {version}, sha256 {}",
            artifact.sha256()
        )
        .unwrap();
        writeln!(generated, "// Coverage: {} files read, {included_files} included, {} recovered structurally; packages {included_packages:?}.", entries.len(), recovered.len()).unwrap();
        audits.push(
            serde_json::json!({"artifact": name, "version": version, "sha256": artifact.sha256(),
            "files_read": entries.len(), "included_files": included_files,
            "packages": included_packages, "recovered": recovered, "files": files}),
        );
    }
    // Language-defined root inheritance, including the implicit Kotlin parent.
    parents
        .entry("kotlin.Annotation".to_owned())
        .or_default()
        .insert("kotlin.Any".to_owned());
    parents
        .entry("scala.AnyRef".to_owned())
        .or_default()
        .insert("scala.Any".to_owned());
    parents
        .entry("scala.Predef".to_owned())
        .or_default()
        .insert("scala.AnyRef".to_owned());
    parents
        .entry("scala.Predef".to_owned())
        .or_default()
        .insert("scala.runtime.stdLibPatches.Predef".to_owned());
    writeln!(
        generated,
        "// Scala 3 compiler patches scala.runtime.stdLibPatches.Predef into scala.Predef."
    )
    .unwrap();
    for provider in ["scala.Predef", "scala"] {
        let mut pending = vec![provider.to_owned()];
        let mut visited = BTreeSet::new();
        while let Some(owner) = pending.pop() {
            if !visited.insert(owner.clone()) {
                continue;
            }
            if let Some(names) = members.get(&owner) {
                packages
                    .entry(provider.to_owned())
                    .or_default()
                    .extend(names.iter().map(|(name, _)| name.clone()));
            }
            if let Some(bases) = parents.get(&owner) {
                pending.extend(bases.iter().cloned());
            }
        }
    }
    let jdk = root.join("jdk/jdk-21.0.12.1+1");
    let relative = [PathBuf::from("jmods/java.base.jmod")];
    let artifact = read_exact_source_set(&jdk, &relative, 16, 8, &limits).unwrap();
    let jmod = read_exact_artifact_while(&jdk.join(&relative[0]), &limits, || false).unwrap();
    let request = jdk_artifact_request(
        jdk,
        ExternalArtifactKind::JdkJmodSet,
        "21.0.12.1+1-LTS",
        vec![],
    );
    let production = crate::analyzer::jvm::jmod_artifact::JdkJmodSetPackProducer
        .produce_loaded_artifact(&request, &limits, None, &artifact);
    assert_eq!(
        production.completeness,
        Completeness::Complete,
        "{:?}",
        production.diagnostics
    );
    let mut object_members = Vec::new();
    let mut java_types = 0;
    for shard in production.pack.expect("JDK declarations").shards {
        let AuthoredPayload::DeclarationFacts { types, members, .. } = shard.payload else {
            continue;
        };
        let object_id = types
            .iter()
            .find(|t| t.name == "java.lang.Object")
            .map(|t| t.id.clone())
            .unwrap();
        for t in types {
            if let Some((package, name)) = t.name.rsplit_once('.')
                && package == "java.lang"
                && t.visibility == Visibility::Public
            {
                packages
                    .entry(package.to_owned())
                    .or_default()
                    .insert(name.to_owned());
                java_types += 1;
            }
        }
        for member in members {
            if member.owner == object_id && member.member_kind != MemberKind::Constructor {
                let visibility = match member.visibility {
                    Visibility::Protected => "protected",
                    _ => "public",
                };
                object_members.push((member.name, visibility.to_owned()));
            }
        }
    }
    object_members.sort();
    assert_eq!(object_members.len(), 11, "pinned Object overload inventory");
    writeln!(
        generated,
        "// java.base.jmod, Temurin 21.0.12.1+1-LTS, sha256 {}",
        jmod.sha256()
    )
    .unwrap();
    writeln!(generated, "// Coverage: 1 module file read, 0 recovered structurally; packages [java.lang]; {java_types} public top-level types; 11 Object methods.").unwrap();
    let mut closed_generated = String::new();
    emit_closed_owners(
        &root,
        &limits,
        &kotlin_members,
        &kotlin_parents,
        &mut generated,
        &mut closed_generated,
        &mut audits,
    );
    writeln!(
        generated,
        "pub(super) const DEFAULT_PROVIDER_NAMES: &[(&str, &[&str])] = &["
    )
    .unwrap();
    for (package, names) in &packages {
        writeln!(generated, "    ({package:?}, &[").unwrap();
        for name in names {
            writeln!(generated, "        {name:?},").unwrap();
        }
        writeln!(generated, "    ]),").unwrap();
    }
    writeln!(
        generated,
        "];\npub(super) const ROOT_MEMBERS: &[(&str, &[super::IntrinsicMember])] = &["
    )
    .unwrap();
    for root in [
        "java.lang.Object",
        "kotlin.Any",
        "kotlin.Annotation",
        "scala.Any",
        "scala.AnyRef",
    ] {
        let mut names = BTreeSet::new();
        let mut visited = BTreeSet::new();
        let mut pending = vec![root.to_owned()];
        while let Some(owner) = pending.pop() {
            if !visited.insert(owner.clone()) {
                continue;
            }
            names.extend(members.get(&owner).into_iter().flatten().cloned());
            if let Some(bases) = parents.get(&owner) {
                pending.extend(bases.iter().cloned());
            }
        }
        let names = if root == "java.lang.Object" {
            object_members.clone()
        } else {
            names.into_iter().collect()
        };
        assert!(!names.is_empty(), "root inventory {root} must be populated");
        writeln!(generated, "    ({root:?}, &[").unwrap();
        for (name, visibility) in names {
            writeln!(
                generated,
                "        super::IntrinsicMember {{ name: {name:?}, visibility: {visibility:?} }},"
            )
            .unwrap();
        }
        writeln!(generated, "    ]),").unwrap();
    }
    writeln!(generated, "];").unwrap();
    generated.push_str(&closed_generated);
    std::fs::write(
        output.with_extension("audit.json"),
        serde_json::to_vec_pretty(&audits).unwrap(),
    )
    .unwrap();
    assert!(
        coverage_failures.is_empty(),
        "uncovered default-package files: {coverage_failures:#?}"
    );
    assert!(
        packages["kotlin.collections"].contains("ArraysUtilJVM"),
        "Java-authored top-level classes must be included in Kotlin default packages"
    );
    assert!(
        packages["scala.Predef"].contains("summon") && packages["scala.Predef"].contains("nn"),
        "Scala 3's compiler-injected Predef names must never support false absence"
    );
    std::fs::write(output, generated).unwrap();
}

/// Recover only declarations in the default scala package. Template bodies
/// are opaque here; package bodies and top-level extension bodies are scopes.
fn scala_top_level_names(root: tree_sitter::Node<'_>, source: &str) -> BTreeSet<String> {
    use brokk_bifrost_jvm::scala::wildcard_imports::scala_enclosing_package_segments_at;
    let mut names = BTreeSet::new();
    let mut pending = brokk_bifrost_core::analyzer::tree_walk::named_children(root);
    while let Some(node) = pending.pop() {
        match node.kind() {
            "package_clause" | "package_object" => {
                if node.kind() == "package_object" {
                    let parent = scala_enclosing_package_segments_at(
                        root,
                        source,
                        node.start_byte().saturating_sub(1),
                    );
                    if parent == ["scala"]
                        && let Some(name) = node.child_by_field_name("name")
                    {
                        names.insert(name.utf8_text(source.as_bytes()).unwrap().to_owned());
                    }
                }
                if let Some(body) = node.child_by_field_name("body") {
                    pending.extend(brokk_bifrost_core::analyzer::tree_walk::named_children(
                        body,
                    ));
                }
            }
            "class_definition"
            | "object_definition"
            | "trait_definition"
            | "enum_definition"
            | "type_definition"
            | "function_definition"
            | "function_declaration"
            | "val_definition"
            | "var_definition"
            | "val_declaration"
            | "var_declaration"
            | "given_definition" => {
                let package = scala_enclosing_package_segments_at(root, source, node.start_byte());
                if package == ["scala"]
                    && let Some(name) = node.child_by_field_name("name")
                {
                    names.insert(name.utf8_text(source.as_bytes()).unwrap().to_owned());
                }
            }
            "extension_definition" | "ERROR" => {
                pending.extend(brokk_bifrost_core::analyzer::tree_walk::named_children(
                    node,
                ));
            }
            _ => {}
        }
    }
    names
}

// Sorted by name then kind (Callable, Value, Type); visibility is metadata,
// never part of the uniqueness key. Public wins a union of access levels.
type NameSet = BTreeMap<(String, u8), String>;
type OwnerMembers = BTreeMap<String, NameSet>;

fn insert_name(names: &mut NameSet, name: String, kind: u8, visibility: &str) {
    let access_rank = |access: &str| match access {
        "public" => 0,
        "protected" => 1,
        "internal" => 2,
        "package" => 3,
        "private" => 4,
        _ => panic!("unknown visibility {access}"),
    };
    names
        .entry((name, kind))
        .and_modify(|old| {
            if access_rank(visibility) < access_rank(old) {
                *old = visibility.to_owned();
            }
        })
        .or_insert_with(|| visibility.to_owned());
}

fn union_names(target: &mut NameSet, source: &NameSet) {
    for ((name, kind), visibility) in source {
        insert_name(target, name.clone(), *kind, visibility);
    }
}

fn source_parent_paths(
    language: Language,
    tree: &tree_sitter::Tree,
    parsed: &ParsedFile,
    declaration: &CodeUnit,
    source: &str,
) -> Vec<Vec<String>> {
    match language {
        Language::Kotlin => {
            let node =
                crate::analyzer::jvm::kotlin_artifact::declaration_node(tree, parsed, declaration)
                    .expect("Kotlin declaration AST range");
            brokk_bifrost_jvm::kotlin::supertypes::extract_kotlin_supertype_segments(node, source)
        }
        Language::Scala => {
            let Some(canonical) = parsed
                .source_facts
                .as_ref()
                .and_then(|facts| facts.scala.as_ref())
            else {
                return Vec::new();
            };
            parsed
                .source_declaration_units
                .iter()
                .filter(|(_, unit)| unit == declaration)
                .filter_map(|(id, _)| {
                    canonical
                        .declarations
                        .iter()
                        .find(|fact| fact.declaration == *id)
                })
                .filter_map(|fact| fact.generic_owner.as_ref())
                .flat_map(|generic| {
                    generic
                        .supertypes
                        .iter()
                        .map(|parent| parent.segments.clone())
                })
                .collect()
        }
        _ => unreachable!(),
    }
}

fn qualify_source_parent(package: &str, segments: &[String]) -> String {
    if segments.len() == 1 {
        format!("{package}.{}", segments[0])
    } else {
        segments.join(".")
    }
}

fn collect_kotlin_closure_inputs(
    tree: &tree_sitter::Tree,
    parsed: &ParsedFile,
    source: &str,
    members: &mut OwnerMembers,
    parents: &mut BTreeMap<String, BTreeSet<String>>,
) {
    let index = crate::analyzer::jvm::parent_index(parsed);
    for declaration in parsed
        .declarations()
        .iter()
        .filter(|unit| !unit.is_synthetic())
    {
        let owner = declaration.fq_name();
        if declaration.kind() == CodeUnitType::Class {
            members.entry(owner.clone()).or_default();
            for segments in source_parent_paths(Language::Kotlin, tree, parsed, declaration, source)
            {
                let path = if segments.len() == 1
                    && matches!(segments[0].as_str(), "Any" | "CharSequence" | "Comparable")
                {
                    format!("kotlin.{}", segments[0])
                } else if segments.len() > 1 && segments[0].starts_with(char::is_uppercase) {
                    format!("{}.{}", declaration.package_name(), segments.join("."))
                } else {
                    qualify_source_parent(declaration.package_name(), &segments)
                };
                parents.entry(owner.clone()).or_default().insert(path);
            }
        }
        if let Some(parent) = index.get(declaration) {
            let kind = match declaration.kind() {
                CodeUnitType::Function => 0,
                CodeUnitType::Field => 1,
                CodeUnitType::Class => 2,
                _ => continue,
            };
            use brokk_bifrost_jvm::kotlin::declarations::{
                KotlinDeclaredVisibility, kotlin_declared_visibility,
            };
            let node =
                crate::analyzer::jvm::kotlin_artifact::declaration_node(tree, parsed, declaration)
                    .expect("Kotlin declaration AST");
            if matches!(node.kind(), "primary_constructor" | "secondary_constructor") {
                continue;
            }
            let visibility = match kotlin_declared_visibility(node, source) {
                KotlinDeclaredVisibility::Public => "public",
                KotlinDeclaredVisibility::Protected => "protected",
                KotlinDeclaredVisibility::Internal => "internal",
                KotlinDeclaredVisibility::Private => "private",
            };
            insert_name(
                members.entry(parent.fq_name()).or_default(),
                declaration.terminal_name().to_owned(),
                kind,
                visibility,
            );
        }
    }
}

fn visibility_name(visibility: Visibility) -> &'static str {
    match visibility {
        Visibility::Public => "public",
        Visibility::Protected => "protected",
        Visibility::Private => "private",
        _ => "package",
    }
}

/// JavaBeans decapitalization preserves leading acronym spellings.
fn bean_name(suffix: &str) -> Option<String> {
    let mut chars = suffix.chars();
    let first = chars.next()?;
    if !first.is_ascii_uppercase() {
        return None;
    }
    if chars
        .next()
        .is_some_and(|second| second.is_ascii_uppercase())
    {
        Some(suffix.to_owned())
    } else {
        Some(format!(
            "{}{}",
            first.to_ascii_lowercase(),
            &suffix[first.len_utf8()..]
        ))
    }
}

fn read_java_closures(path: &std::path::Path, limits: &ArtifactProducerLimits) -> OwnerMembers {
    use crate::analyzer::jvm::java_artifact::{
        JavaClassSurfaceOutcome, class_inventory_names, class_surface,
    };
    use brokk_bifrost_analysis::analyzer::semantic_model::TypeRef;
    use std::io::Read;
    let artifact = read_exact_artifact_while(path, limits, || false).unwrap();
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(artifact.bytes())).unwrap();
    let entries = (0..archive.len())
        .filter_map(|i| {
            let entry = archive.by_index(i).unwrap();
            let entry_name = entry.name().expect("archive entry name");
            let name = entry_name.strip_prefix("classes/").unwrap_or(&entry_name);
            name.strip_suffix(".class")
                .map(|name| (name.replace(['/', '$'], "."), i))
        })
        .collect::<BTreeMap<_, _>>();
    let mut members = OwnerMembers::new();
    let mut parents = BTreeMap::<String, BTreeSet<String>>::new();
    let mut pending = KOTLIN_JAVA_MAPPINGS
        .iter()
        .map(|(_, java)| java.replace('$', "."))
        .collect::<Vec<_>>();
    let mut visited = BTreeSet::new();
    while let Some(owner) = pending.pop() {
        if !visited.insert(owner.clone()) {
            continue;
        }
        let i = entries
            .get(&owner)
            .unwrap_or_else(|| panic!("missing {owner} in {path:?}"));
        let mut entry = archive.by_index(*i).unwrap();
        let name = entry.name().expect("archive entry name").into_owned();
        let mut bytes = Vec::new();
        entry.read_to_end(&mut bytes).unwrap();
        let mut remaining = limits.max_records;
        let mut hit = false;
        let mut diagnostics = BoundedProducerDiagnostics::new(limits);
        let JavaClassSurfaceOutcome::Declared(surface) = class_surface(
            "inventory",
            &name,
            &bytes,
            limits.max_signature_depth,
            &mut remaining,
            &mut hit,
            &mut diagnostics,
        ) else {
            panic!("unreadable class {owner}");
        };
        assert!(!hit);
        let (diagnostics, suppressed) = diagnostics.finish();
        assert!(
            diagnostics.is_empty() && suppressed.total() == 0,
            "{owner}: {diagnostics:#?}; {suppressed:#?}"
        );
        let inventory = surface.jvm_inventory.expect("class inventory");
        assert!(
            inventory.types_complete && inventory.supertypes_complete,
            "incomplete hierarchy {owner}"
        );
        for parent in inventory.supertypes {
            let TypeRef::Named { name, .. } = parent.target else {
                panic!("non-nominal parent");
            };
            pending.push(name.clone());
            parents.entry(owner.clone()).or_default().insert(name);
        }
        let names = members.entry(owner.clone()).or_default();
        for nested in inventory.nested_types {
            insert_name(names, nested.name, 2, visibility_name(nested.visibility));
        }
        for (name, kind, visibility, parameters, returns) in
            class_inventory_names(&bytes, limits.max_signature_depth)
        {
            let access = visibility_name(visibility);
            let callable = kind == MemberKind::Method;
            insert_name(names, name.clone(), if callable { 0 } else { 1 }, access);
            if !callable {
                continue;
            }
            let property = if parameters == 0 && returns.is_some() {
                name.strip_prefix("get").and_then(bean_name).or_else(|| {
                    (name.starts_with("is")
                        && matches!(&returns, Some(TypeRef::Named {name, ..}) if name == "boolean"))
                    .then(|| name.clone())
                })
            } else if parameters == 1 && returns.is_none() {
                name.strip_prefix("set").and_then(bean_name)
            } else {
                None
            };
            if let Some(property) = property {
                insert_name(names, property, 1, access);
            }
        }
    }
    let mut closures = OwnerMembers::new();
    for (_, java) in KOTLIN_JAVA_MAPPINGS {
        let owner = java.replace('$', ".");
        let (names, _) = flatten_member_names(
            vec![owner.clone(), "java.lang.Object".to_owned()],
            &parents,
            |parent, names| union_names(names, &members[parent]),
        );
        closures.insert(owner, names);
    }
    closures
}

fn flatten_member_names(
    mut pending: Vec<String>,
    parents: &BTreeMap<String, BTreeSet<String>>,
    mut contribute: impl FnMut(&str, &mut NameSet),
) -> (NameSet, BTreeSet<String>) {
    let mut visited = BTreeSet::new();
    let mut names = NameSet::new();
    while let Some(owner) = pending.pop() {
        if !visited.insert(owner.clone()) {
            continue;
        }
        contribute(&owner, &mut names);
        pending.extend(parents.get(&owner).into_iter().flatten().cloned());
    }
    (names, visited)
}

fn emit_closed_owners(
    root: &std::path::Path,
    limits: &ArtifactProducerLimits,
    kotlin: &OwnerMembers,
    parents: &BTreeMap<String, BTreeSet<String>>,
    header: &mut String,
    generated: &mut String,
    audits: &mut Vec<serde_json::Value>,
) {
    let mut java_union = OwnerMembers::new();
    let mut java21 = OwnerMembers::new();
    writeln!(
        header,
        "// Closed-owner envelope: Kotlin 2.1.20, 2.2.20, 2.3.20; JDK 8, 11, 17, 21, 25; mapping-table v1."
    )
    .unwrap();
    for (file, version) in [
        ("jdk8/rt.jar", "Corretto 8.0.472"),
        ("jdk11/java.base.jmod", "Corretto 11.0.28"),
        ("jdk17/java.base.jmod", "Corretto 17.0.16"),
        (
            "jdk/jdk-21.0.12.1+1/jmods/java.base.jmod",
            "Temurin 21.0.12.1+1",
        ),
        ("jdk25/java.base.jmod", "Corretto 25.0.1"),
    ] {
        let path = root.join(file);
        let artifact = read_exact_artifact_while(&path, limits, || false).unwrap();
        writeln!(
            header,
            "// {file}, version {version}, sha256 {}",
            artifact.sha256()
        )
        .unwrap();
        let closures = read_java_closures(&path, limits);
        if version.starts_with("Temurin 21") {
            java21 = closures.clone();
        }
        for (owner, names) in &closures {
            union_names(java_union.entry(owner.clone()).or_default(), names);
        }
        audits.push(serde_json::json!({"closed_java_input": file, "version": version, "sha256": artifact.sha256(), "owners": audit_names(&closures)}));
    }
    let mut closed = OwnerMembers::new();
    for (owner, _) in KOTLIN_JAVA_MAPPINGS
        .iter()
        .filter(|(owner, _)| *owner == "kotlin.String" || owner.starts_with("kotlin.collections."))
    {
        let (names, visited) = flatten_member_names(
            vec![(*owner).to_owned(), "kotlin.Any".to_owned()],
            parents,
            |parent, names| {
                union_names(
                    names,
                    kotlin
                        .get(parent)
                        .unwrap_or_else(|| panic!("missing Kotlin ancestor {parent}")),
                );
                if let Some((_, java)) = KOTLIN_JAVA_MAPPINGS.iter().find(|(k, _)| *k == parent) {
                    union_names(names, &java_union[&java.replace('$', ".")]);
                }
            },
        );
        closed.insert((*owner).to_owned(), names);
        audits.push(serde_json::json!({"closed_kotlin_owner": owner, "kotlin_ancestors": visited}));
    }
    // Literal and fixed-universe String identities also use the JVM spelling.
    closed.insert(
        "java.lang.String".to_owned(),
        closed["kotlin.String"].clone(),
    );
    for (owner, names) in &closed {
        writeln!(header, "// {owner}: {} members (name, kind).", names.len()).unwrap();
    }
    writeln!(
        generated,
        "pub(super) const CLOSED_OWNER_MEMBERS: &[(&str, &[super::ClosedOwnerMember])] = &["
    )
    .unwrap();
    for (owner, names) in &closed {
        writeln!(generated, "    ({owner:?}, &[").unwrap();
        for ((name, kind), visibility) in names {
            let kind = ["Callable", "Value", "Type"][*kind as usize];
            writeln!(generated, "        super::ClosedOwnerMember {{ name: {name:?}, kind: super::ClosedMemberKind::{kind}, visibility: {visibility:?} }},").unwrap();
        }
        writeln!(generated, "    ]),").unwrap();
    }
    writeln!(generated, "];").unwrap();
    let extras = java_union
        .iter()
        .map(|(owner, names)| {
            (
                owner.clone(),
                names
                    .keys()
                    .filter(|key| !java21[owner].contains_key(*key))
                    .map(|(name, kind)| serde_json::json!([name, kind]))
                    .collect::<Vec<_>>(),
            )
        })
        .collect::<BTreeMap<_, _>>();
    audits.push(serde_json::json!({"closed_owner_members": audit_names(&closed), "jdk_union_minus_21": extras, "kotlin_direct": audit_names(kotlin), "kotlin_parents": parents}));
}

fn audit_names(owners: &OwnerMembers) -> serde_json::Value {
    serde_json::Value::Object(owners.iter().map(|(owner, names)| (owner.clone(), serde_json::json!(names.iter().map(|((name, kind), visibility)| serde_json::json!({"name":name, "kind":kind, "visibility":visibility})).collect::<Vec<_>>()))).collect())
}
