/// How often the background writer appends a `totals` line.
///
/// A one-shot corpus run is killed by `timeout` and never returns from `main`,
/// so the totals cannot be written only at exit.
const TOTALS_INTERVAL: Duration = Duration::from_secs(5);

macro_rules! seam_methods {
    ($($variant:ident => $name:literal, $owner:literal;)*) => {
        /// One method of one reader trait. The fixed-size counter table is
        /// indexed by this; nothing here grows with the workspace.
        #[derive(Clone, Copy, PartialEq, Eq, Debug)]
        #[repr(usize)]
        pub enum SeamMethod {
            $($variant,)*
        }

        impl SeamMethod {
            /// Every method of both traits, in declaration order.
            pub const ALL: &'static [Self] = &[$(Self::$variant,)*];

            /// The method's Rust name, which is what the digest reports.
            pub const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $name,)*
                }
            }

            /// Which of the two traits declares it.
            pub const fn owner(self) -> &'static str {
                match self {
                    $(Self::$variant => $owner,)*
                }
            }
        }
    };
}

