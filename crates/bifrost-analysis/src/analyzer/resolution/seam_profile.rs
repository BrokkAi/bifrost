/// A typed read keyed on a request batch, streaming rows through the caller's
/// page visitor. Thirty-four of the thirty-nine typed methods are this shape.
macro_rules! counted_typed_pages {
    ($method:ident, $variant:ident, $key:ty, $row:ty) => {
        fn $method(
            &self,
            request: TypedFactRequest<'_, $key>,
            cancellation: &CancellationToken,
            visitor: &mut TypedFactPageVisitor<'_, $row>,
        ) -> StoreResult<TypedFactReadOutcome> {
            record_call(SeamMethod::$variant, request.len());
            visitor.count_rows_as(Some(SeamMethod::$variant));
            let outcome = self.inner.$method(request, cancellation, visitor);
            visitor.count_rows_as(None);
            outcome
        }
    };
}

