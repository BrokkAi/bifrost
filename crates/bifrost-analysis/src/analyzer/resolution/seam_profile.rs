/// The number of methods the two traits declare between them.
pub const METHOD_COUNT: usize = SeamMethod::ALL.len();

#[derive(Default)]
struct MethodCounters {
    calls: AtomicU64,
    keys: AtomicU64,
    rows: AtomicU64,
}

impl MethodCounters {
    fn snapshot(&self) -> (u64, u64, u64) {
        (
            self.calls.load(Ordering::Relaxed),
            self.keys.load(Ordering::Relaxed),
            self.rows.load(Ordering::Relaxed),
        )
    }
}

