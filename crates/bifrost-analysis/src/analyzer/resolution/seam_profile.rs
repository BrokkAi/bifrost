//! Per-method counters on the reader seam.
//!
//! The reader seam is the pair of traits through which the language-neutral
//! evaluator reads facts: [`BatchResolutionFragmentSource`] (21 methods) and
//! [`SelectedTypedFactSource`] (39 methods). Nothing counted them. The counts
//! that existed were one layer down (interior indexes) or two layers down (SQL
//! statements), so "which question does a request ask most" could only be
//! answered by a proxy. This module answers it directly: for every one of the
//! sixty methods it records calls, keys requested and rows handed back, per
//! request and per process.
//!
//! The instrument is off unless `BIFROST_SEAM_PROFILE` names an output file.
//! The variable is read once per process. With it unset every counting site is
//! one `Option` test against a value the optimizer can hoist, and no request
//! observes any other difference.
//!
//! # Where the one counting point is
//!
//! Counting happens in [`SeamProfiled`], a forwarding decorator whose sixty
//! methods are generated by the macros below. It counts at the trait, not in
//! an implementor, so it survives milestone 6 replacing every implementor: the
//! only thing that moves is the single line that wraps a source.
//!
//! Operation factories borrow their existing lexical and typed SQL reader
//! handles through this decorator. The evaluator and demand builders use the
//! observed trait views; inherent metadata and context-token queries keep the
//! same raw handles. Internal SQL reader delegation remains inside the borrow,
//! so it neither creates a second cache nor counts a second seam call.
//!
//! # Rows
//!
//! A method that returns its rows is counted from what it returns. A method
//! that streams pages through a visitor is counted at the visitor:
//! [`TypedFactPageVisitor::count_rows_as`] tags the caller's visitor with the
//! method that is reading through it, and `visit_page` adds the page's length.
//! Wrapping the visitor in a second visitor was rejected: a visitor carries the
//! resolution session's scope-step charge, so a wrapper would charge the budget
//! twice and change what a request answers.
//!
//! # Output
//!
//! JSON lines. One `request` line per MCP tool call, carrying the tool name,
//! the wall time and that request's per-method deltas. One `totals` line every
//! [`TOTALS_INTERVAL`] and at the end of every request, so a process killed by
//! `timeout` (the warm `usage_graph` workload does not finish) still leaves its
//! counts behind. The digest reads the last `totals` line.

