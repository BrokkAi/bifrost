struct Profile {
    started: Instant,
    methods: [MethodCounters; METHOD_COUNT],
    go_reverse: GoReverseCounters,
    rename_phases: [RenamePhaseCounters; 4],
    output: Mutex<std::fs::File>,
    requests: AtomicU64,
    /// Nonzero while a request boundary is open. The per-request deltas are a
    /// difference of two process-wide snapshots, which is exact only while one
    /// request is open at a time; a line taken while this was above one says so.
    in_flight: AtomicUsize,
    dirty: AtomicBool,
}

impl Profile {
    fn open(path: &std::path::Path) -> Option<Self> {
        match std::fs::File::create(path) {
            Ok(output) => Some(Self {
                started: Instant::now(),
                methods: std::array::from_fn(|_| MethodCounters::default()),
                go_reverse: GoReverseCounters::default(),
                rename_phases: std::array::from_fn(|_| RenamePhaseCounters::default()),
                output: Mutex::new(output),
                requests: AtomicU64::new(0),
                in_flight: AtomicUsize::new(0),
                dirty: AtomicBool::new(true),
            }),
            Err(error) => {
                eprintln!(
                    "Bifrost seam profile could not create {}: {error}",
                    path.display()
                );
                None
            }
        }
    }

    fn snapshot(&self) -> Vec<(u64, u64, u64)> {
        self.methods.iter().map(MethodCounters::snapshot).collect()
    }

    fn go_reverse_snapshot(&self) -> [u64; 18] {
        self.go_reverse.snapshot()
    }

    fn rename_phase_snapshot(&self) -> [[u64; 5]; 4] {
        std::array::from_fn(|phase| {
            let counters = &self.rename_phases[phase];
            [
                counters.calls.load(Ordering::Relaxed),
                counters.wall_nanos.load(Ordering::Relaxed),
                counters.sql_executions.load(Ordering::Relaxed),
                counters.sql_rows.load(Ordering::Relaxed),
                counters.sql_nanos.load(Ordering::Relaxed),
            ]
        })
    }

    fn write_line(&self, line: &str) {
        super::write_profile_line(
            &self.output,
            line,
            "seam profile output poisoned",
            "seam profile",
        );
    }
}

static PROFILE: OnceLock<Option<Profile>> = OnceLock::new();

/// The process's profile, or `None` when [`PROFILE_PATH_ENV`] is unset. The
/// environment is read exactly once, on the first seam call or request scope.
fn profile() -> Option<&'static Profile> {
    PROFILE
        .get_or_init(|| {
            let path = PathBuf::from(std::env::var_os(PROFILE_PATH_ENV)?);
            let profile = Profile::open(&path)?;
            profile.write_line(&header_line());
            spawn_totals_writer();
            Some(profile)
        })
        .as_ref()
}

/// Whether the instrument is on in this process.
pub fn enabled() -> bool {
    profile().is_some()
}

fn header_line() -> String {
    let methods = SeamMethod::ALL
        .iter()
        .map(|method| serde_json::json!({"method": method.as_str(), "trait": method.owner()}))
        .collect::<Vec<_>>();
    serde_json::json!({
        "kind": "header",
        "pid": std::process::id(),
        "method_count": METHOD_COUNT,
        "totals_interval_ms": TOTALS_INTERVAL.as_millis(),
        "methods": methods,
    })
    .to_string()
}

fn spawn_totals_writer() {
    let spawned = std::thread::Builder::new()
        .name("bifrost-seam-profile".to_string())
        .spawn(|| {
            loop {
                std::thread::sleep(TOTALS_INTERVAL);
                write_totals();
            }
        });
    if let Err(error) = spawned {
        eprintln!("Bifrost seam profile has no background writer: {error}");
    }
}

/// Append a `totals` line now. With the variable unset it does nothing.
pub fn write_totals() {
    let Some(profile) = profile() else {
        return;
    };
    if !profile.dirty.swap(false, Ordering::Relaxed) {
        return;
    }
    let counters = profile.snapshot();
    let line = serde_json::json!({
        "kind": "totals",
        "uptime_ms": profile.started.elapsed().as_millis(),
        "requests": profile.requests.load(Ordering::Relaxed),
        "methods": method_object(&counters, None),
    })
    .to_string();
    profile.write_line(&line);
}

/// Count one native Go reverse target and the provisional candidate sites it
/// yielded. These counters are inert unless the seam profile is enabled.
pub fn record_go_reverse_candidates(candidates: usize) {
    let Some(profile) = profile() else {
        return;
    };
    profile.go_reverse.targets.fetch_add(1, Ordering::Relaxed);
    profile
        .go_reverse
        .candidate_sites
        .fetch_add(candidates as u64, Ordering::Relaxed);
    profile.dirty.store(true, Ordering::Relaxed);
}

/// Count candidate sites admitted to the forward-confirmation stage.
pub fn record_go_reverse_forward_candidates(candidates: usize) {
    let Some(profile) = profile() else {
        return;
    };
    profile
        .go_reverse
        .forward_candidate_sites
        .fetch_add(candidates as u64, Ordering::Relaxed);
    profile.dirty.store(true, Ordering::Relaxed);
}

