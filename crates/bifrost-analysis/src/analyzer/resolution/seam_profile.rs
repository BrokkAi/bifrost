/// Every method whose call count moved, as `{name: {calls, keys, rows}}`.
fn method_object(now: &[(u64, u64, u64)], before: Option<&[(u64, u64, u64)]>) -> serde_json::Value {
    let mut object = serde_json::Map::new();
    for (index, method) in SeamMethod::ALL.iter().enumerate() {
        let (calls, keys, rows) = now[index];
        let (calls, keys, rows) = match before {
            Some(before) => (
                calls - before[index].0,
                keys - before[index].1,
                rows - before[index].2,
            ),
            None => (calls, keys, rows),
        };
        if calls == 0 {
            continue;
        }
        object.insert(
            method.as_str().to_string(),
            serde_json::json!({"calls": calls, "keys": keys, "rows": rows}),
        );
    }
    serde_json::Value::Object(object)
}

fn record_call(method: SeamMethod, keys: usize) {
    let Some(profile) = profile() else {
        return;
    };
    let counters = &profile.methods[method as usize];
    counters.calls.fetch_add(1, Ordering::Relaxed);
    counters.keys.fetch_add(keys as u64, Ordering::Relaxed);
    profile.dirty.store(true, Ordering::Relaxed);
}

/// Add rows handed to the caller. Called from the return of a method that
/// returns its rows, and from [`TypedFactPageVisitor::visit_page`] for a
/// method that streams them.
pub(super) fn record_rows(method: SeamMethod, rows: usize) {
    let Some(profile) = profile() else {
        return;
    };
    profile.methods[method as usize]
        .rows
        .fetch_add(rows as u64, Ordering::Relaxed);
}

/// One request boundary. Its `Drop` writes the request's line.
///
/// It is a scope and not a pair of calls so that an early return, a `?` or a
/// panic in the tool still closes the request.
pub struct RequestScope {
    inner: Option<OpenRequest>,
}

struct OpenRequest {
    tool: String,
    started: Instant,
    before: Vec<(u64, u64, u64)>,
    sql_before: Option<(u64, u64, u128)>,
    go_reverse_before: [u64; 18],
    rename_phase_before: [[u64; 5]; 4],
    overlapped: bool,
}

/// Open a request boundary for one MCP tool call. A no-op when the instrument
/// is off.
pub fn request_scope(tool: &str) -> RequestScope {
    let Some(profile) = profile() else {
        return RequestScope { inner: None };
    };
    let overlapped = profile.in_flight.fetch_add(1, Ordering::Relaxed) > 0;
    RequestScope {
        inner: Some(OpenRequest {
            tool: tool.to_string(),
            started: Instant::now(),
            before: profile.snapshot(),
            sql_before: brokk_bifrost_core::cache_db::sql_profile::totals_with_rows(),
            go_reverse_before: profile.go_reverse_snapshot(),
            rename_phase_before: profile.rename_phase_snapshot(),
            overlapped,
        }),
    }
}

impl Drop for RequestScope {
    fn drop(&mut self) {
        let Some(open) = self.inner.take() else {
            return;
        };
        let profile = profile().expect("an open request scope implies a profile");
        let overlapped = open.overlapped || profile.in_flight.fetch_sub(1, Ordering::Relaxed) > 1;
        let now = profile.snapshot();
        let go_reverse_now = profile.go_reverse_snapshot();
        let rename_phase_now = profile.rename_phase_snapshot();
        profile.requests.fetch_add(1, Ordering::Relaxed);
        let mut line = serde_json::json!({
            "kind": "request",
            "tool": open.tool,
            "wall_ms": open.started.elapsed().as_secs_f64() * 1000.0,
            "overlapped": overlapped,
            "methods": method_object(&now, Some(&open.before)),
        });
        let go_reverse: [u64; 18] =
            std::array::from_fn(|index| go_reverse_now[index] - open.go_reverse_before[index]);
        line["native_go_reverse"] = serde_json::json!({
            "targets": go_reverse[0],
            "candidate_sites": go_reverse[1],
            "candidate_sites_per_target": if go_reverse[0] == 0 { 0.0 } else { go_reverse[1] as f64 / go_reverse[0] as f64 },
            "forward_candidate_sites": go_reverse[2],
            "forward_batches": go_reverse[3],
            "forward_answers": go_reverse[4],
            "prepared_contexts": go_reverse[5],
            "summary_confirmed_sites": go_reverse[6],
            "fallbacks": {
                "unit_summary_unavailable": go_reverse[7],
                "incomplete_provider": go_reverse[8],
                "conflicting_names": go_reverse[9],
                "crossed_summary_unavailable": go_reverse[10],
                "qualified_import_missing": go_reverse[11],
                "overlay": go_reverse[12],
                "alias_unresolved": go_reverse[13],
            },
            "candidate_diagnostics": {
                "path_site_key_mismatch": go_reverse[14],
                "not_name_reference": go_reverse[15],
            },
            "member_access_sites": go_reverse[16],
            "member_access_unknown_sites": go_reverse[17],
        });
        let rename_phases = GoRenamePhase::ALL
            .into_iter()
            .map(|phase| {
                let now = rename_phase_now[phase as usize];
                let before = open.rename_phase_before[phase as usize];
                (
                    phase.name().to_owned(),
                    serde_json::json!({
                        "calls": now[0] - before[0],
                        "wall_ms": (now[1] - before[1]) as f64 / 1_000_000.0,
                        "statements": now[2] - before[2],
                        "rows": now[3] - before[3],
                        "sql_ms": (now[4] - before[4]) as f64 / 1_000_000.0,
                    }),
                )
            })
            .collect::<serde_json::Map<_, _>>();
        line["rename_phases"] = serde_json::Value::Object(rename_phases);
        if let (
            Some((executions, rows, nanos)),
            Some((before_executions, before_rows, before_nanos)),
        ) = (
            brokk_bifrost_core::cache_db::sql_profile::totals_with_rows(),
            open.sql_before,
        ) {
            line["sql"] = serde_json::json!({
                "executions": executions - before_executions,
                "rows": rows - before_rows,
                "nanos": (nanos - before_nanos).to_string(),
            });
        }
        profile.write_line(&line.to_string());
        write_totals();
    }
}

/// One counted reader source.
///
/// Every method forwards to `inner` and records one call, the keys the call
/// asked for (a batch's length, or one for a scalar question) and the rows the
/// call handed back. This is a shared view: the mutable exclusion entrypoint
/// forwards to the inner shared entrypoint, as the shared engine adapter does.
pub struct SeamProfiled<'a, T: ?Sized> {
    inner: &'a T,
}

impl<'a, T: ?Sized> SeamProfiled<'a, T> {
    pub(crate) const fn observing(inner: &'a T) -> Self {
        Self { inner }
    }
}

fn counted_rust_trait_lookup(
    method: SeamMethod,
    lookup: impl FnOnce() -> StoreResult<RustImplementedTraits>,
) -> StoreResult<RustImplementedTraits> {
    record_call(method, 1);
    let outcome = lookup();
    if let Ok(RustImplementedTraits::Traits(traits)) = &outcome {
        record_rows(method, traits.len());
    }
    outcome
}

fn counted_reference_seed_batches(
    method: SeamMethod,
    key_count: usize,
    visitor: &mut dyn FnMut(&ReferenceSeedBatch) -> StoreResult<bool>,
    visit: impl FnOnce(
        &mut dyn FnMut(&ReferenceSeedBatch) -> StoreResult<bool>,
    ) -> StoreResult<ResolutionCompletion>,
) -> StoreResult<ResolutionCompletion> {
    record_call(method, key_count);
    let mut counting = |batch: &ReferenceSeedBatch| {
        record_rows(method, batch.len());
        visitor(batch)
    };
    visit(&mut counting)
}

/// A method whose keys and rows are both known from its arguments and its
/// return value.
macro_rules! counted {
    ($method:ident ( $($argument:ident : $type:ty),* $(,)? ) -> $return:ty,
     $variant:ident, keys = $keys:expr, rows = |$result:ident| $rows:expr) => {
        fn $method(&self, $($argument: $type),*) -> $return {
            let keys = $keys;
            let _key_scope = brokk_bifrost_core::cache_db::sql_profile::key_scope(keys);
            record_call(SeamMethod::$variant, keys);
            let outcome = self.inner.$method($($argument),*);
            if let Ok($result) = &outcome {
                record_rows(SeamMethod::$variant, $rows);
            }
            outcome
        }
    };
}

/// A method that streams `&[BatchCandidateMatch]` pages through a closure.
macro_rules! counted_candidate_pages {
    ($method:ident, $variant:ident $(, $extra:ident : $extra_type:ty)*) => {
        fn $method(
            &self,
            requests: &[BatchCandidateRequest],
            $($extra: $extra_type,)*
            cancellation: &CancellationToken,
            visitor: &mut dyn FnMut(&[BatchCandidateMatch]) -> StoreResult<bool>,
        ) -> StoreResult<BatchCandidateCompletionOutcome> {
            let keys = requests.len();
            let _key_scope = brokk_bifrost_core::cache_db::sql_profile::key_scope(keys);
            record_call(SeamMethod::$variant, keys);
            let mut counting = |page: &[BatchCandidateMatch]| {
                record_rows(SeamMethod::$variant, page.len());
                visitor(page)
            };
            self.inner.$method(requests, $($extra,)* cancellation, &mut counting)
        }
    };
}

