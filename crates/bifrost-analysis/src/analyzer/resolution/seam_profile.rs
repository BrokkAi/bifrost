#[derive(Default)]
struct RenamePhaseCounters {
    calls: AtomicU64,
    wall_nanos: AtomicU64,
    sql_executions: AtomicU64,
    sql_rows: AtomicU64,
    sql_nanos: AtomicU64,
}

#[derive(Clone, Copy)]
#[repr(usize)]
pub(crate) enum GoRenamePhase {
    CandidateEnumeration,
    Confirmation,
    CaptureCheck,
    EditAssembly,
}

impl GoRenamePhase {
    const ALL: [Self; 4] = [
        Self::CandidateEnumeration,
        Self::Confirmation,
        Self::CaptureCheck,
        Self::EditAssembly,
    ];

    const fn name(self) -> &'static str {
        match self {
            Self::CandidateEnumeration => "candidate_enumeration",
            Self::Confirmation => "confirmation",
            Self::CaptureCheck => "capture_check",
            Self::EditAssembly => "edit_assembly",
        }
    }
}

struct OpenGoRenamePhase {
    profile: &'static Profile,
    phase: GoRenamePhase,
    started: Instant,
    sql_before: Option<(u64, u64, u128)>,
}

/// Phase timer for native Go rename, inert unless the existing seam profile is on.
pub(crate) struct GoRenamePhaseScope {
    inner: Option<OpenGoRenamePhase>,
}

pub(crate) fn go_rename_phase(phase: GoRenamePhase) -> GoRenamePhaseScope {
    let Some(profile) = profile() else {
        return GoRenamePhaseScope { inner: None };
    };
    GoRenamePhaseScope {
        inner: Some(OpenGoRenamePhase {
            profile,
            phase,
            started: Instant::now(),
            sql_before: brokk_bifrost_core::cache_db::sql_profile::totals_with_rows(),
        }),
    }
}

impl Drop for GoRenamePhaseScope {
    fn drop(&mut self) {
        let Some(open) = self.inner.take() else {
            return;
        };
        let counters = &open.profile.rename_phases[open.phase as usize];
        counters.calls.fetch_add(1, Ordering::Relaxed);
        counters.wall_nanos.fetch_add(
            u64::try_from(open.started.elapsed().as_nanos()).unwrap_or(u64::MAX),
            Ordering::Relaxed,
        );
        if let (
            Some((executions, rows, nanos)),
            Some((before_executions, before_rows, before_nanos)),
        ) = (
            brokk_bifrost_core::cache_db::sql_profile::totals_with_rows(),
            open.sql_before,
        ) {
            counters.sql_executions.fetch_add(
                executions.saturating_sub(before_executions),
                Ordering::Relaxed,
            );
            counters
                .sql_rows
                .fetch_add(rows.saturating_sub(before_rows), Ordering::Relaxed);
            counters.sql_nanos.fetch_add(
                u64::try_from(nanos.saturating_sub(before_nanos)).unwrap_or(u64::MAX),
                Ordering::Relaxed,
            );
        }
        open.profile.dirty.store(true, Ordering::Relaxed);
    }
}

